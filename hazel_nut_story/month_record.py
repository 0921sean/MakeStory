for line in july_text.splitlines():
    parts = line.strip().split()
    if len(parts) >= 6:
        plan = " ".join(parts[3:-2])
        start, end = parts[-2], parts[-1]
        duration = to_minutes(end) - to_minutes(start)
        if duration > 0:
            plan_durations[plan] += duration

# ✅ 6. 상위 6개 + 기타 분류
